using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Corvid.Tools.Generators;

/// <summary>
/// Emits a <c>ToolFunction</c> subclass for each <c>[Tool]</c> method: argument binding by direct calls, the JSON Schema
/// as a string written at compile time, and the risk metadata from <c>[SideEffect]</c>, <c>[Network]</c> and
/// <c>[Destructive]</c>. The containing partial class gains <c>CreateTools()</c>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ToolGenerator : IIncrementalGenerator
{
    internal const string ToolAttribute = "Corvid.Tools.ToolAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ToolModel> tools = context.SyntaxProvider.ForAttributeWithMetadataName(
            ToolAttribute,
            static (node, _) => node is MethodDeclarationSyntax,
            static (context, cancellationToken) => ToolParser.Parse((IMethodSymbol)context.TargetSymbol, context.Attributes[0], cancellationToken));

        // Collected because duplicate names are an assembly-wide check.
        context.RegisterSourceOutput(tools.Collect(), static (context, tools) => Emit(context, tools));
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<ToolModel> tools)
    {
        var duplicates = new HashSet<string>(tools.GroupBy(t => t.ToolName).Where(g => g.Count() > 1).Select(g => g.Key));
        var valid = new List<ToolModel>();
        foreach (ToolModel tool in tools)
        {
            foreach (DiagnosticInfo diagnostic in tool.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (duplicates.Contains(tool.ToolName))
            {
                context.ReportDiagnostic(Diagnostic.Create(Diagnostics.DuplicateName, tool.Location?.ToLocation(), tool.ToolName));
            }
            else if (tool.Diagnostics.Length == 0)
            {
                valid.Add(tool);
            }
        }

        foreach (IGrouping<string, ToolModel> type in valid.GroupBy(t => t.TypeMetadataName).OrderBy(g => g.Key, System.StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            context.AddSource($"{type.Key}.Tools.g.cs", Render([.. type.OrderBy(t => t.ToolName, System.StringComparer.Ordinal)]));
        }
    }

    private static string Render(IReadOnlyList<ToolModel> tools)
    {
        ToolModel first = tools[0];
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine("#nullable enable");
        code.AppendLine();
        string indent = "";
        if (first.Namespace.Length > 0)
        {
            code.AppendLine($"namespace {first.Namespace}");
            code.AppendLine("{");
            indent = "    ";
        }

        string provider = first.TypeIsStatic ? "" : " : global::Corvid.Tools.IToolProvider";
        code.AppendLine($"{indent}{(first.TypeIsStatic ? "static " : "")}partial {first.TypeKeyword} {first.TypeName}{provider}");
        code.AppendLine($"{indent}{{");

        string create = first.TypeIsStatic ? "public static" : "public";
        string construct = first.TypeIsStatic ? "()" : "(this)";
        code.AppendLine($"{indent}    /// <summary>Wrappers for this type's [Tool] methods, generated at compile time.</summary>");
        code.AppendLine($"{indent}    {create} global::System.Collections.Generic.IReadOnlyList<global::Corvid.Tools.ToolFunction> CreateTools() => new global::Corvid.Tools.ToolFunction[]");
        code.AppendLine($"{indent}    {{");
        foreach (ToolModel tool in tools)
        {
            code.AppendLine($"{indent}        new {tool.ClassName}{construct},");
        }

        code.AppendLine($"{indent}    }};");

        foreach (ToolModel tool in tools)
        {
            string i = indent + "    ";
            code.AppendLine();
            code.AppendLine($"{i}private sealed class {tool.ClassName} : global::Corvid.Tools.ToolFunction");
            code.AppendLine($"{i}{{");
            code.AppendLine($"{i}    private static readonly global::Corvid.Tools.ToolDescriptor Descriptor_ = {tool.DescriptorExpression};");
            code.AppendLine();
            if (first.TypeIsStatic)
            {
                code.AppendLine($"{i}    public {tool.ClassName}()");
                code.AppendLine($"{i}        : base(Descriptor_)");
                code.AppendLine($"{i}    {{");
                code.AppendLine($"{i}    }}");
            }
            else
            {
                code.AppendLine($"{i}    private readonly global::{first.TypeMetadataName} _target;");
                code.AppendLine();
                code.AppendLine($"{i}    public {tool.ClassName}(global::{first.TypeMetadataName} target)");
                code.AppendLine($"{i}        : base(Descriptor_)");
                code.AppendLine($"{i}    {{");
                code.AppendLine($"{i}        _target = target;");
                code.AppendLine($"{i}    }}");
            }

            code.AppendLine();
            code.AppendLine($"{i}    protected override {(tool.IsAsync ? "async " : "")}global::System.Threading.Tasks.ValueTask<object?> InvokeCoreAsync(global::Microsoft.Extensions.AI.AIFunctionArguments arguments, global::System.Threading.CancellationToken cancellationToken)");
            code.AppendLine($"{i}    {{");
            foreach (string line in tool.Body.Split('\n'))
            {
                code.AppendLine($"{i}        {line}".TrimEnd());
            }

            code.AppendLine($"{i}    }}");
            if (tool.Helpers.Length > 0)
            {
                foreach (string line in tool.Helpers.Split('\n'))
                {
                    code.AppendLine(line.Length == 0 ? "" : $"{i}    {line}");
                }
            }

            code.AppendLine($"{i}}}");
        }

        code.AppendLine($"{indent}}}");
        if (first.Namespace.Length > 0)
        {
            code.AppendLine("}");
        }

        return code.ToString();
    }
}
