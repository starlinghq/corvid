using System.Collections.Immutable;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Corvid.Abstractions.Extraction;
using Corvid.Models.Privacy;
using Corvid.Secrets;

namespace S3.Gliner2Targets;

public sealed record CredentialRow(int Id, string Split, string Kind, string Text, ImmutableArray<PiiEntity> Entities);

/// <summary>
/// The credential detector (C-032) beside GLiNER2 in the privacy egress gate. On <c>fixtures/credentials.jsonl</c> (written
/// and split before the detector existed; scored on the report half) and on S3's <c>pii.jsonl</c> (through the committed
/// GLiNER2 predictions): the detector alone, GLiNER2 alone at the gate's threshold, and both together, by covered recall as
/// <see cref="PiiEval"/> scores it, plus spans with no labelled value behind them. Then the detector alone over the 300
/// commands of the targets corpus and <c>everyday.txt</c>, as realistic text holding no credentials.
/// </summary>
public static class CredentialEval
{
    private const int MinValueLength = 2; // PrivacyEgressOptions.MinValueLength's default

    public static async Task<int> RunAsync(string repo)
    {
        var folder = Corpus.Folder(repo);
        var rows = File.ReadLines(Path.Combine(folder, "fixtures", "credentials.jsonl"))
            .Where(line => line.Trim().Length > 0)
            .Select(line => JsonSerializer.Deserialize<CredentialRow>(line, Corpus.Json)!).ToList();
        Validate(rows);

        // GLiNER2 once over the fixture, as the gate calls it: the default labels at the default threshold.
        Model.RequireMallocSetting();
        var threshold = EgressPolicy.Default.Threshold;
        var model = new Dictionary<int, List<ExtractedSpan>>();
        var raw = new StringBuilder();
        using (var extractor = Model.Load())
        {
            foreach (var row in rows)
            {
                var result = await extractor.ExtractAsync(new ExtractionRequest(row.Text, EgressPolicy.Default.AllLabels, threshold));
                raw.AppendLine(JsonSerializer.Serialize(new { threshold, id = row.Id, spans = result.Spans }, Corpus.Json));
                model[row.Id] = Kept(result.Spans, threshold);
            }
        }

        var md = new StringBuilder();
        md.AppendLine("# Credential values in the privacy egress gate (C-032)");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"Generated by `S3.Gliner2Targets credentials`. Detector rules: `CredentialDetector.Egress` (shapes and labelled values). " +
            $"GLiNER2: gliner2-base-v1 on the CPU, labels {string.Join(", ", EgressPolicy.Default.AllLabels)}, threshold {threshold:0.0}, with the gate's filters. " +
            $"A value is covered when every non-space character lies inside some span (`PiiEval.Covered`); a span is a false positive when it neither contains nor lies within a labelled value of its text.");

        md.AppendLine();
        md.AppendLine("## credentials.jsonl");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"{rows.Count} texts: {rows.Count(r => !r.Entities.IsEmpty)} with {rows.Sum(r => r.Entities.Length)} credential values " +
            $"({string.Join(", ", rows.Where(r => !r.Entities.IsEmpty).GroupBy(r => r.Kind).Select(g => $"{g.Key} {g.Count()}"))}), " +
            $"{rows.Count(r => r.Entities.IsEmpty)} hard negatives. Split per kind by SHA-256 of the text: " +
            $"report {rows.Count(r => r.Split == "report")}, tune {rows.Count(r => r.Split == "tune")}. The fixture was committed before the detector; the detector was tuned on the tune half only.");
        foreach (var half in new[] { "report", "tune" })
        {
            var subset = rows.Where(r => r.Split == half).Select(r => (r.Id, r.Text, r.Entities)).ToList();
            md.AppendLine();
            md.AppendLine(CultureInfo.InvariantCulture, $"### {(half == "report" ? "Report half (the measurement)" : "Tune half")}");
            Score(md, subset, model, perKind: rows.ToDictionary(r => r.Id, r => r.Kind));
        }

        // S3's PII fixture through the committed predictions: the model is not run again.
        var pii = File.ReadLines(Path.Combine(folder, "fixtures", "pii.jsonl")).Where(line => line.Trim().Length > 0)
            .Select(line => JsonSerializer.Deserialize<PiiRow>(line, Corpus.Json)!).ToList();
        var piiModel = new Dictionary<int, List<ExtractedSpan>>();
        foreach (var line in File.ReadLines(Path.Combine(folder, "results", "pii-predictions.jsonl")).Where(line => line.Trim().Length > 0))
        {
            var prediction = JsonSerializer.Deserialize<PiiPrediction>(line, Corpus.Json)!;
            if (Math.Abs(prediction.Threshold - threshold) < 1e-6)
                piiModel[prediction.Id] = Kept(prediction.Spans, threshold);
        }
        md.AppendLine();
        md.AppendLine("## pii.jsonl (spike S3, seen data)");
        md.AppendLine();
        md.AppendLine("GLiNER2 spans are the committed `results/pii-predictions.jsonl` at 0.4. Only credential values are gold here; the other PII values count as gold for the false-positive column, so a span on a name is not a false positive.");
        var credentialGold = pii.Select(r => (r.Id, r.Text, Entities: r.Entities.Where(e => e.Label == "credential").ToImmutableArray(), All: r.Entities)).ToList();
        Score(md, [.. credentialGold.Select(r => (r.Id, r.Text, r.Entities))], piiModel, perKind: null,
            falsePositiveGold: credentialGold.ToDictionary(r => r.Id, r => r.All));
        var nonCredential = pii.Where(r => r.Entities.All(e => e.Label != "credential")).ToList();
        var piiFalse = nonCredential.SelectMany(r => Detect(r.Text).Select(s => (r.Id, s))).ToList();
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"Detector spans on the {nonCredential.Count} texts without a credential: {piiFalse.Count}" +
            $"{(piiFalse.Count == 0 ? "." : ": " + string.Join(", ", piiFalse.Select(p => $"`{p.s.Text}` (text {p.Id})")))}");

        // Realistic negatives: shell commands and everyday commands, which hold digests, hosts and paths but no credentials.
        var commands = File.ReadLines(Path.Combine(folder, "fixtures", "targets-corpus.jsonl"))
            .Select(line => JsonSerializer.Deserialize<CorpusRow>(line, Corpus.Json)!.Command).ToList();
        var everyday = File.ReadLines(Path.Combine(folder, "everyday.txt"))
            .Select(line => line.Trim()).Where(line => line.Length > 0 && !line.StartsWith('#')).ToList();
        md.AppendLine();
        md.AppendLine("## Detector alone on text with no credentials");
        md.AppendLine();
        md.AppendLine("| Set | Texts | Texts with a detector span | Spans |");
        md.AppendLine("| --- | --- | --- | --- |");
        var listed = new List<string>();
        foreach (var (name, texts) in new[] { ("targets-corpus.jsonl commands", commands), ("everyday.txt", everyday) })
        {
            var hits = texts.Select(text => (Text: text, Spans: Detect(text))).Where(hit => hit.Spans.Count > 0).ToList();
            md.AppendLine(CultureInfo.InvariantCulture, $"| {name} | {texts.Count} | {hits.Count} | {hits.Sum(hit => hit.Spans.Count)} |");
            listed.AddRange(hits.SelectMany(hit => hit.Spans.Select(span => $"- {name}: `{span.Text}` in `{hit.Text}`")));
        }
        if (listed.Count > 0)
        {
            md.AppendLine();
            foreach (var line in listed)
                md.AppendLine(line);
        }

        var results = Path.Combine(folder, "results");
        Directory.CreateDirectory(results);
        File.WriteAllText(Path.Combine(results, "credentials-predictions.jsonl"), raw.ToString());
        File.WriteAllText(Path.Combine(results, "credentials.md"), md.ToString());
        Console.WriteLine(md.ToString());
        return 0;
    }

    private sealed record PiiPrediction(float Threshold, int Id, ImmutableArray<ExtractedSpan> Spans);

    private static void Score(StringBuilder md, List<(int Id, string Text, ImmutableArray<PiiEntity> Entities)> rows,
        Dictionary<int, List<ExtractedSpan>> model, Dictionary<int, string>? perKind,
        Dictionary<int, ImmutableArray<PiiEntity>>? falsePositiveGold = null)
    {
        var detector = rows.ToDictionary(r => r.Id, r => Detect(r.Text));
        var combined = rows.ToDictionary(r => r.Id, r => detector[r.Id].Concat(model[r.Id]).ToList());
        var gold = rows.SelectMany(r => r.Entities.Select(e => (Row: r, Entity: e))).ToList();
        var texts = rows.Count;
        var negatives = rows.Count(r => r.Entities.IsEmpty);
        ImmutableArray<PiiEntity> Gold((int Id, string Text, ImmutableArray<PiiEntity> Entities) row) =>
            falsePositiveGold is null ? row.Entities : falsePositiveGold[row.Id];
        int False(Dictionary<int, List<ExtractedSpan>> spans, bool negativesOnly) => rows
            .Where(r => !negativesOnly || r.Entities.IsEmpty)
            .Sum(r => spans[r.Id].Count(s => !Gold(r).Any(e => PiiEval.Related(s.Text.Trim(), e.Text))));

        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"{texts} texts, {gold.Count} credential values, {negatives} texts with none.");
        md.AppendLine();
        md.AppendLine("| Source | Covered recall | False-positive spans | per text | on texts with no credential |");
        md.AppendLine("| --- | --- | --- | --- | --- |");
        foreach (var (name, spans) in new[] { ("Detector alone", detector), ("GLiNER2 alone (0.4, any label)", model), ("Gate: both", combined) })
        {
            var covered = gold.Count(g => PiiEval.Covered(g.Row.Text, g.Entity.Text, spans[g.Row.Id]));
            var falseSpans = False(spans, negativesOnly: false);
            md.AppendLine(CultureInfo.InvariantCulture, $"| {name} | {PiiEval.Ratio(covered, gold.Count)} | {falseSpans} | " +
                $"{(texts == 0 ? 0 : falseSpans / (double)texts):0.00} | {False(spans, negativesOnly: true)} on {negatives} |");
        }

        if (perKind is not null)
        {
            md.AppendLine();
            md.AppendLine("| Kind | Values | Detector | GLiNER2 | Both |");
            md.AppendLine("| --- | --- | --- | --- | --- |");
            foreach (var group in gold.GroupBy(g => perKind[g.Row.Id]).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                int Count(Dictionary<int, List<ExtractedSpan>> spans) => group.Count(g => PiiEval.Covered(g.Row.Text, g.Entity.Text, spans[g.Row.Id]));
                md.AppendLine(CultureInfo.InvariantCulture, $"| {group.Key} | {group.Count()} | {Count(detector)} | {Count(model)} | {Count(combined)} |");
            }
        }

        var missed = gold.Where(g => !PiiEval.Covered(g.Row.Text, g.Entity.Text, combined[g.Row.Id])).ToList();
        md.AppendLine();
        md.AppendLine(missed.Count == 0 ? "Every credential value is covered by the gate." : "Credential values the gate would send:");
        if (missed.Count > 0)
        {
            md.AppendLine();
            foreach (var (row, entity) in missed)
                md.AppendLine(CultureInfo.InvariantCulture, $"- `{entity.Text}` (text {row.Id}; detector {(PiiEval.Covered(row.Text, entity.Text, detector[row.Id]) ? "covers" : "misses")})");
        }
        var detectorFalse = rows.SelectMany(r => detector[r.Id].Where(s => !Gold(r).Any(e => PiiEval.Related(s.Text.Trim(), e.Text))).Select(s => (r.Id, s))).ToList();
        md.AppendLine();
        md.AppendLine(detectorFalse.Count == 0 ? "No detector span lacks a labelled value." : "Detector spans with no labelled value behind them:");
        if (detectorFalse.Count > 0)
        {
            md.AppendLine();
            foreach (var (id, span) in detectorFalse)
                md.AppendLine(CultureInfo.InvariantCulture, $"- `{span.Text}` (text {id})");
        }
    }

    // What the gate keeps of the detector's matches: the value, trimmed, at least PrivacyEgress.MinCredentialLength (4) long.
    private static List<ExtractedSpan> Detect(string text) =>
    [
        .. CredentialDetector.Find(text, CredentialDetector.Egress)
            .Where(match => match.ValueIn(text).Trim().Length >= 4)
            .Select(match => new ExtractedSpan(PrivacyEgress.CredentialLabel, match.ValueIn(text), match.Start, match.End, 1f)),
    ];

    private static List<ExtractedSpan> Kept(ImmutableArray<ExtractedSpan> spans, float threshold) =>
        [.. spans.Where(s => s.Confidence >= threshold && s.Text.Trim().Length >= MinValueLength && s.Text.Any(char.IsLetterOrDigit))];

    // The split must be the one committed with the fixture: per kind, ordered by SHA-256 of the text, alternating.
    private static void Validate(List<CredentialRow> rows)
    {
        foreach (var row in rows)
            foreach (var entity in row.Entities)
                if (!row.Text.Contains(entity.Text, StringComparison.Ordinal) || entity.Label != "credential")
                    throw new InvalidDataException($"Credential row {row.Id}: '{entity.Text}' is not in its text or not a credential.");
        foreach (var group in rows.GroupBy(row => row.Kind))
        {
            var index = 0;
            foreach (var row in group.OrderBy(row => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(row.Text))), StringComparer.Ordinal))
                if (row.Split != (index++ % 2 == 0 ? "tune" : "report"))
                    throw new InvalidDataException($"Credential row {row.Id}: split '{row.Split}' is not the hash split.");
        }
    }
}
